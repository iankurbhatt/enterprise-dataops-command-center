from __future__ import annotations

import datetime as dt
from typing import Any, Dict
import pandas as pd


def generate_postmortem_report(rca_bundle: Dict[str, Any], scenario_name: str) -> str:
    """
    Generate a comprehensive ServiceNow / Confluence Incident Post-Mortem & RCA document.
    """
    inc = rca_bundle["incident"]
    whys_md = "\n".join([f"- **{w.split(':')[0]}:** {w.split(':', 1)[1].strip()}" for w in rca_bundle["five_whys"]])
    now_str = dt.datetime.now().strftime("%Y-%m-%d %H:%M UTC")

    return f"""# INCIDENT POST-MORTEM & ROOT CAUSE ANALYSIS (RCA)
**Document ID:** `PM-{inc['servicenow_id']}` | **Linked JIRA:** `{inc['jira_ticket']}`  
**Generated By:** Ankur Bhatt — Data Operations & Analytics Command Center  
**Timestamp:** {now_str} | **Operational Scenario:** {scenario_name}

---

## 1. Executive Incident Summary
| Attribute | Operational Telemetry |
| :--- | :--- |
| **ServiceNow Ticket** | `{inc['servicenow_id']}` ({inc['priority']}) |
| **Engineering JIRA Key** | `{inc['jira_ticket']}` |
| **Incident Title** | {inc['incident_title']} |
| **Affected Pipeline / DAG** | `{inc['affected_pipeline']}` ({inc['scheduler_engine']}) |
| **Upstream Producer** | `{inc['upstream_source']}` |
| **Downstream Business Impact** | {rca_bundle['downstream_impact']} |
| **Impacted Records Quarantined** | **{inc['impacted_records']:,} records** |
| **Commercial Revenue at Risk** | **${inc['revenue_at_risk_usd']:,.2f} USD** |
| **Resolution MTTR vs. SLA** | **{inc['mttr_mins']} mins** (Target SLA: {inc['sla_target_mins']} mins — `{inc['sla_status']}`) |

---

## 2. Systematic 5-Whys Root Cause Analysis
**Primary Root Cause Classification:** `{inc['root_cause_category']}`

{whys_md}

---

## 3. Remediation & Preventive Engineering Controls
### Immediate DataOps Containment (Executed)
> {rca_bundle['immediate_remediation']}

### Long-Term Preventive Architecture Fix
> {rca_bundle['preventive_action']}

### Production SQL / Python Remediation Patch
```sql
{rca_bundle['patch_snippet']}
```

---

## 4. Governance & Compliance Sign-Off
- **Data Integrity Verification:** Silver layer (`orders_clean`, `payments_clean`) reconciled with 100% schema & constraint pass rate post-quarantine.
- **Dead-Letter Queue (DLQ) Audit:** All {inc['impacted_records']:,} anomalous records isolated in `quarantine_dlq` with rule tag `{inc['rule_id']}`.
"""


