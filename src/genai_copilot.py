def answer_copilot_question(
    question: str,
    summary_metrics: Dict[str, Any],
    incidents_df: pd.DataFrame,
    rule_results: pd.DataFrame,
) -> str:
    """
    Context-aware DataOps AI Assistant that answers stakeholder or interviewer questions
    using live metrics from the active pipeline run.
    """
    q = question.lower()
    top_inc = incidents_df.iloc[0]
    worst_rule = rule_results.sort_values("records_failed", ascending=False).iloc[0]

    if any(k in q for k in ["revenue", "risk", "money", "financial", "exposure", "leakage"]):
        return (
            f"### Commercial Revenue at Risk Analysis\n"
            f"- **Total Financial Exposure Intercepted:** **${summary_metrics['total_revenue_at_risk_usd']:,.2f} USD** across **{summary_metrics['total_quarantined_rows']:,} quarantined records**.\n"
            f"- **Largest Single Risk Contributor:** `{top_inc['servicenow_id']}` (*{top_inc['incident_title']}*) representing **${top_inc['revenue_at_risk_usd']:,.2f} USD** across {top_inc['impacted_records']:,} records.\n"
            f"- **Protection Mechanism:** All high-risk records were automatically intercepted before reaching the Gold General Ledger and Power BI executive dashboards."
        )
    if any(k in q for k in ["p1", "incident", "servicenow", "jira", "ticket", "mttr", "sla"]):
        p1_df = incidents_df[incidents_df["priority"] == "P1 - Critical"]
        lines = [
            f"- **`{r['servicenow_id']}` / `{r['jira_ticket']}`** ({r['priority']}): {r['incident_title']} — **{r['impacted_records']} records** | **${r['revenue_at_risk_usd']:,.2f}** | MTTR: `{r['mttr_mins']}m`"
            for _, r in p1_df.iterrows()
        ]
        return (
            f"### Active P1 Critical Incidents ({len(p1_df)} Total)\n"
            + "\n".join(lines)
            + f"\n\n**Overall Mean Time To Resolution (MTTR):** `{incidents_df['mttr_mins'].mean():.1f} mins` (100% compliant with enterprise SLA targets)."
        )
    if any(k in q for k in ["root cause", "rca", "why", "webhook", "duplicate", "orphan"]):
        return (
            f"### Systematic Root Cause Summary\n"
            f"1. **Webhook Retry Storm (`RULE-01` & `RULE-05`):** Upstream gateway timeouts triggered exponential POST retries; resolved via deterministic `ROW_NUMBER()` primary-key deduplication.\n"
            f"2. **Orphan Payment Captures (`RULE-06`):** 15-minute CDC replication skew between streaming Stripe webhooks and batch SAP ERP orders; mitigated via a 20-minute CDC Holding Queue.\n"
            f"3. **Schema & Null Drift (`RULE-02` & `RULE-04`):** Unannounced upstream field rename (`merchant_region` -> `territory_code`); remediated via coalesced field mapping and country lookup imputation."
        )
    return (
        f"### DataOps Sentinel Live Status Brief\n"
        f"- **Composite Data Health Score:** **{summary_metrics['overall_health_score']:.2f}%**\n"
        f"- **Highest Volume Anomaly Rule:** `{worst_rule['rule_id']}` (*{worst_rule['rule_name']}*) with **{worst_rule['records_failed']} failed records** ({worst_rule['pass_rate_pct']}% pass rate).\n"
        f"- **Production Readiness:** **{summary_metrics['orders_clean_count']:,} clean orders** and **{summary_metrics['payments_clean_count']:,} clean payments** validated and loaded into the Silver SQLite warehouse."
    )
